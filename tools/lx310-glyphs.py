"""
Epson LX-310 / ESC-P 9-pin draft character generator bitmaps.

Each glyph is written as 9 ROWS, top to bottom, exactly as the character looks
on paper. Row index 0 is pin 1 (top of a capital), row 6 is the baseline
(pin 7), rows 7-8 are the two descender pins (8-9). '#' fires a pin, '.' does
not. The builder transposes these rows into print-head columns.

Geometry, traced from the Jaynath slip scan (the GJ03BV 5655 / 43450 / 12575 /
30875 lines) rather than from the manual's idealised draft grid:
  - Character advance measured 20.5 px against an 18 px ink width, i.e. the
    glyph inks ~88% of the cell. Encoded here as 10 ink columns out of an
    11-column advance; the builder maps that onto the 1/10 in cell.
  - Seven pin rows span the cap height (row 0 top, row 6 on the baseline).
    Measured row pitch is 3.5-4.3 px against a 2.05 px column pitch, so rows
    are roughly 1.7-2x farther apart than columns.
  - Horizontal strokes on this unit print as SOLID continuous bars, not the
    dotted '# # #' runs of textbook draft mode. The scan shows unbroken top,
    middle and bottom bars on B G 3 5 6 E and friends: the head is effectively
    double-striking, so adjacent columns do both ink. Reproducing the dotted
    runs instead is what made the previous font read as a different typeface.
  - Dot diameter is ~1/60 in = twice the column step, so dots overlap their
    neighbours by half. That overlap is applied at render time by the builder,
    not encoded here.

Capitals occupy rows 0-6. Lowercase x-height occupies rows 2-6. Descenders
(g j p q y and the comma/semicolon tails) reach rows 7-8.
"""

ROWS = 9
INK_COLS = 10
ADVANCE_COLS = 11       # ink/advance = 10/11 = 0.91, matching the 18/20.5 px
                        # ink-to-advance ratio measured off the slip
BASELINE_ROW = 6

GLYPHS = {}


def g(ch, *rows):
    """Register a glyph from row strings, written top-to-bottom."""
    assert len(rows) <= ROWS, (ch, len(rows))
    rows = list(rows) + ['.' * INK_COLS] * (ROWS - len(rows))
    for r in rows:
        assert len(r) == INK_COLS, (ch, r, len(r))
    GLYPHS[ch] = rows


